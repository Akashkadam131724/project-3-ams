export function iconForNavHref(href: string) {
  if (href === "/projects") return NavIconProjects;
  if (href.includes("/members/activity")) return NavIconActivity;
  if (href.endsWith("/members")) return NavIconMembers;
  if (href.endsWith("/activity")) return NavIconActivity;
  if (href.includes("/folders") || /\/projects\/[^/]+$/.test(href))
    return NavIconFiles;
  if (href.includes("create-user")) return NavIconUserPlus;
  if (href.includes("create-project")) return NavIconFolderPlus;
  if (href.includes("assign-owner")) return NavIconUserCog;
  if (href.includes("/admin/users")) return NavIconUsers;
  return NavIconProjects;
}
